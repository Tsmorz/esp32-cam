# PlatformIO pre-build hook: FW_VERSION from `git describe` (v1.2.0 on a
# release tag, v1.2.0-3-gabc1234 after it, "-dirty" with local changes) into
# src/generated/version.h. Written only when it changes, and only main.cpp
# includes it, so a new commit doesn't rebuild everything.
import os
import subprocess

Import("env")  # noqa: F821 — provided by PlatformIO/SCons

root = env.subst("$PROJECT_DIR")
try:
    version = subprocess.check_output(
        ["git", "describe", "--tags", "--always", "--dirty"],
        cwd=root, text=True, stderr=subprocess.DEVNULL,
    ).strip()
except (OSError, subprocess.CalledProcessError):
    version = "unknown"

out = os.path.join(root, "src", "generated", "version.h")
text = (
    "// Generated by scripts/version.py — do not edit\n"
    "#pragma once\n"
    '#define FW_VERSION "%s"\n' % version
)
if not os.path.exists(out) or open(out).read() != text:
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write(text)
    print("version: " + version)
